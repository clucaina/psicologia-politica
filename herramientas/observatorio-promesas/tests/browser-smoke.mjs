import {chromium} from "playwright";
import assert from "node:assert/strict";
import {pathToFileURL} from "node:url";
import {resolve} from "node:path";
import {mkdirSync} from "node:fs";
const path=resolve("herramientas/observatorio-promesas/index.html");
const browser=await chromium.launch({headless:true});
const errors=[],art=resolve("qa-artifacts");
mkdirSync(art,{recursive:true});
try{
 const page=await browser.newPage({viewport:{width:1380,height:900},acceptDownloads:true});
 page.on("pageerror",err=>errors.push(err.message));
 await page.goto(pathToFileURL(path).href);
 await page.locator("#demo").click();
 assert.equal(await page.locator(".record").count(),1);
 assert.match(await page.locator("#titleView").innerText(),/300 viviendas/);
 await page.locator("#title").fill("Programa de viviendas ficticio, revisión 2");
 assert.equal(await page.locator("#titleView").innerText(),"Programa de viviendas ficticio, revisión 2");
 await page.locator("#srcName").fill("BOCG ficticio de contraste");
 await page.locator("#srcURL").fill("https://www.congreso.es/es/datos-abiertos");
 await page.locator("#srcNote").fill("Una votación parlamentaria no acredita por sí sola la ejecución de una promesa municipal.");
 await page.locator("#sourceForm button[type=submit]").click();
 assert.equal(await page.locator(".evidence-item").count(),2);
 const downloaded=page.waitForEvent("download");
 await page.locator("#export").click();
 const d=await downloaded;
 assert.match(d.suggestedFilename(),/observatorio-promesas\.json/);
 await page.reload();
 assert.equal(await page.locator("#titleView").innerText(),"Programa de viviendas ficticio, revisión 2");
 assert.equal(await page.locator(".evidence-item").count(),2);
 await page.screenshot({path:resolve(art,"promesas-desktop.png"),fullPage:true});
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 mobile.on("pageerror",err=>errors.push("mobile: "+err.message));
 await mobile.goto(pathToFileURL(path).href);
 await mobile.locator("#demo").click();
 const dims=await mobile.evaluate(()=>({scroll:document.documentElement.scrollWidth,width:innerWidth}));
 assert.ok(dims.scroll<=dims.width+2,JSON.stringify(dims));
 await mobile.screenshot({path:resolve(art,"promesas-mobile.png"),fullPage:true});
 assert.deepEqual(errors,[]);
 console.log("Browser QA PASSED: add/edit/source/export/reload, responsive mobile and no JS errors");
}finally{await browser.close();}
